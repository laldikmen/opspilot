"""The model-selection tables: every model on every selection period, and how sure the lead is.

Written to reports/selection_tables.md by `make train`, so the numbers quoted in
reports/model_selection.md always come from code. The test set is not used.
"""

from pathlib import Path

import numpy as np
import pandas as pd

from opspilot.config import REPORTS_DIR
from opspilot.models.baselines import BASELINES
from opspilot.models.metrics import paired_bootstrap
from opspilot.models.selection import evaluate_periods, predict_on_periods

REPORT_PATH = REPORTS_DIR / "selection_tables.md"
# The final model is compared with the strongest learned and the strongest rule baseline.
RIVALS = ["logistic_regression", "route_rate_rule"]


def compare_models(
    features: pd.DataFrame, final_predictions: dict[str, pd.DataFrame], final_name: str
) -> tuple[pd.DataFrame, pd.DataFrame]:
    """A results table per model and period, and paired bootstraps of the final model's lead."""
    predictions = {name: predict_on_periods(features, fp) for name, fp in BASELINES.items()}
    predictions[final_name] = final_predictions

    rows = []
    for name, by_period in predictions.items():
        results = evaluate_periods(by_period)
        rows.append(
            {
                "model": name,
                **{f"{period} lift": r["lift"] for period, r in results.items()},
                "mean lift": np.mean([r["lift"] for r in results.values()]),
                "mean ROC-AUC": np.mean([r["roc_auc"] for r in results.values()]),
                "mean top-10% recall": np.mean([r["recall_top10"] for r in results.values()]),
                "mean Brier": np.mean([r["brier"] for r in results.values()]),
            }
        )
    table = pd.DataFrame(rows).set_index("model")

    bootstrap = []
    for rival in RIVALS:
        for period, ours in final_predictions.items():
            theirs = predictions[rival][period]
            difference, low, high = paired_bootstrap(ours.y, ours.p, theirs.p)
            bootstrap.append(
                {
                    "compared with": rival,
                    "period": period,
                    "lift difference": difference,
                    "95% low": low,
                    "95% high": high,
                }
            )
    return table, pd.DataFrame(bootstrap)


def markdown_table(frame: pd.DataFrame, digits: int = 3) -> str:
    frame = frame.reset_index() if frame.index.name else frame
    header = "| " + " | ".join(map(str, frame.columns)) + " |"
    rule = "| " + " | ".join("---" for _ in frame.columns) + " |"
    body = [
        "| " + " | ".join(f"{v:.{digits}f}" if isinstance(v, float) else str(v) for v in row) + " |"
        for row in frame.itertuples(index=False)
    ]
    return "\n".join([header, rule, *body])


def write_selection_report(
    table: pd.DataFrame,
    bootstrap: pd.DataFrame,
    backtest_results: pd.DataFrame,
    backtest_summary: pd.DataFrame,
    late_rates: dict[str, float],
    commit: str,
    path: Path = REPORT_PATH,
) -> Path:
    brier = backtest_results.pivot(index="strategy", columns="period", values="brier")
    calibration = brier.join(backtest_summary).sort_values("mean_brier")
    sections = [
        "# Model selection tables",
        f"Generated by `make train` at commit `{commit[:7]}`; do not edit by hand. Folds and "
        "validation only, the test set is not used. Lift is PR-AUC divided by the period's "
        "late rate. Every fit only learns from orders whose outcome was known when its scored "
        "period starts (ADR 0004).",
        "Late rate per period: "
        + ", ".join(f"{period} {100 * rate:.1f}%" for period, rate in late_rates.items())
        + ".",
        "## Every model on every period",
        markdown_table(table),
        "## How sure is the final model's lead?",
        "Paired bootstrap of the lift difference, 1,000 resamples of the scored orders.",
        markdown_table(bootstrap),
        "## Calibration backtest",
        "Brier score of each strategy on each period, fitted only on earlier periods and only "
        "on outcomes known when that period starts (ADR 0006).",
        markdown_table(calibration, digits=4),
    ]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n\n".join(sections) + "\n")
    return path
